#!/usr/bin/env python3
"""Generate ritzlib/README.md's module table from the modules (AGAST #3913).

The hand-kept table listed 31 of 45 modules, two of which (crt0.ritz,
testing.ritz) were not in the tree (#1859).  Each module now carries its own
description as its first line, `# ritzlib/<path> - <description>`, and the
README block between BEGIN and END is rendered from those lines.

    python3 tools/ritzlib_modules.py            # exit 1 if the table is stale
    python3 tools/ritzlib_modules.py --write    # regenerate it

test_ritzlib_modules.py::test_readme_table_is_current runs the check in
`make tools-unit`.
"""

import argparse
import re
import sys
from pathlib import Path, PurePosixPath

BEGIN = "<!-- BEGIN module table: generated by tools/ritzlib_modules.py --write -->"
END = "<!-- END module table -->"

HEADER = re.compile(r"# ritzlib/(\S+\.ritz) - (.+)")


def modules(ritzlib):
    """[(path under ritzlib/, description)] for every module, sorted.

    ritzlib/tests/ is a package of tests, not modules.  A module whose first
    line is not its own header is a ValueError naming it.
    """
    out = []
    for path in sorted(Path(ritzlib).rglob("*.ritz")):
        rel = PurePosixPath(path.relative_to(ritzlib).as_posix())
        if rel.parts[0] == "tests":
            continue
        first = path.read_text(encoding="utf-8").split("\n", 1)[0]
        match = HEADER.fullmatch(first.rstrip())
        if not match or match.group(1) != str(rel):
            raise ValueError(
                f"ritzlib/{rel}: first line must be `# ritzlib/{rel} - <description>`, "
                f"got {first!r}")
        out.append((str(rel), match.group(2).strip()))
    return sorted(out)


def module_table(ritzlib):
    rows = ["| Module | Import | Description |", "|--------|--------|-------------|"]
    for rel, desc in modules(ritzlib):
        dotted = ".".join(PurePosixPath(rel).with_suffix("").parts)
        rows.append(f"| `{rel}` | `ritzlib.{dotted}` | {desc} |")
    return "\n".join(rows) + "\n"


def render_readme(readme, ritzlib):
    """`readme` with the BEGIN..END block replaced by the current table."""
    start, end = readme.find(BEGIN), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"README has no {BEGIN!r} ... {END!r} marker pair")
    head = readme[:start + len(BEGIN)]
    return f"{head}\n{module_table(ritzlib)}{readme[end:]}"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ritzlib", type=Path,
                        default=Path(__file__).resolve().parent.parent / "ritzlib")
    parser.add_argument("--write", action="store_true", help="rewrite the README table")
    args = parser.parse_args(argv)

    readme_path = args.ritzlib / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    fresh = render_readme(readme, args.ritzlib)
    if fresh == readme:
        print("ritzlib/README.md module table: current")
        return 0
    if args.write:
        readme_path.write_text(fresh, encoding="utf-8")
        print("ritzlib/README.md module table: rewritten")
        return 0
    print("ritzlib/README.md module table is stale: run "
          "`python3 tools/ritzlib_modules.py --write`")
    return 1


if __name__ == "__main__":
    sys.exit(main())
