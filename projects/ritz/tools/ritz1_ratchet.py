#!/usr/bin/env python3
"""Ratchet the M1.3 structural thresholds (AGAST #4433).

`make arch-report` prints ritz_metrics.py's measurements; this script holds
them to a committed baseline so a regression is caught by `make tools-unit`.
Milestone M1.3 (#1830) is "done when ritz-metrics on ritz1/src shows: no fn
> 300 SLOC outside generated code, acyclic module graph, ptr_len_param_pair
<= 40, no silent capacity limits".  None of those was a gate before this.

A metric may improve; it may not get worse.  Improvements pass (so a good
change is never blocked) but do not silently rewrite history: the baseline
is only refreshed by an explicit `--update`, which records the new numbers
for the commit that brought them.  A regression exits 1 and names the
metric, the committed baseline and the measured value.

    ritz1_ratchet.py                     # compare this tree to the baseline
    ritz1_ratchet.py --update            # record this tree's improvements
    ritz1_ratchet.py --measured FILE     # compare a saved measurement
    ritz1_ratchet.py --src DIR --metrics PATH

Generated modules are excluded from the length thresholds by explicit name
(``GENERATED_MODULES``), as M1.3 says "outside generated code".  A size
heuristic would quietly stop excluding `parser_gen` the day ritzgen emits a
smaller file.  The smell counters (ptr_len_param_pair and friends) are
whole-tree, matching the ticket's baseline: they describe the code that
ships, generated or not.

Fast and compiler-free: the only work is reading `*.ritz` (about 2 s for
ritz1/src) and calling ritz-metrics in-process; no build, no subprocess.
"""

from __future__ import annotations

import argparse
import contextlib
import importlib.util
import io
import json
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

_TOOLS = Path(__file__).resolve().parent
if str(_TOOLS) not in sys.path:
    sys.path.insert(0, str(_TOOLS))

import ritz1_arch  # noqa: E402  (needs the path insert above)

FN_SLOC_LIMIT = 300
FILE_SLOC_LIMIT = 3000

# M1.3's "outside generated code".  Names, not a "# Generated by" heuristic
# and not a size threshold: these are the three modules ritzgen writes.
GENERATED_MODULES = ("lexer_scan_gen", "parser_gen", "tokens_gen")
DEFAULT_GENERATED = GENERATED_MODULES

DEFAULT_SRC = ritz1_arch.DEFAULT_SRC
DEFAULT_BASELINE = _TOOLS / "ritz1_metrics_baseline.json"
# projects/ritz/tools -> projects/ritz -> projects -> repo root.
_REPO_ROOT = _TOOLS.parents[2]
DEFAULT_METRICS = (
    _REPO_ROOT / "projects" / "larb" / "tools" / "ritz-metrics" / "ritz_metrics.py"
)

# Scalar counters compared one-way (measured must not exceed baseline).
SCALARS = (
    "hand_fns_over_sloc_limit",
    "hand_files_over_sloc_limit",
    "ptr_len_param_pair",
    "i32_as_bool",
    "cstr_literal",
    "fixed_u8_buffer",
    "cycle_sccs",
    "cycle_modules",
)


@dataclass(frozen=True)
class Finding:
    kind: str  # "regression" or "improvement"
    metric: str
    baseline: object
    measured: object
    detail: str


def _stem(path: str) -> str:
    return Path(path).stem


def load_metrics(src: Path = DEFAULT_SRC, metrics_py: Path = DEFAULT_METRICS) -> dict:
    """Run ritz-metrics in-process and return its --json document.

    Kept in-process so the tools-unit gate spawns no child (tools/conftest.py
    marks subprocess-spawning tests integration) and so `make tools-unit`
    needs nothing but the interpreter.
    """
    if not metrics_py.exists():
        raise FileNotFoundError(f"ritz-metrics not found: {metrics_py}")
    spec = importlib.util.spec_from_file_location("_ritz_metrics", metrics_py)
    if spec is None or spec.loader is None:  # pragma: no cover - defensive
        raise ImportError(f"cannot load {metrics_py}")
    mod = importlib.util.module_from_spec(spec)
    # dataclasses resolve annotation modules through sys.modules; register
    # before exec or the @dataclass in ritz_metrics.py fails.
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    with tempfile.TemporaryDirectory() as td:
        out = Path(td) / "metrics.json"
        sink = io.StringIO()
        with contextlib.redirect_stdout(sink):
            rc = mod.main([str(src), "--json", str(out)])
        if rc != 0:
            raise RuntimeError(f"ritz-metrics failed ({rc}) on {src}")
        return json.loads(out.read_text())


def summarise(
    data: dict,
    *,
    generated_modules: tuple[str, ...] = GENERATED_MODULES,
    cycle_sccs: int = 0,
    cycle_module_names: tuple[str, ...] | list[str] = (),
) -> dict:
    """Reduce ritz-metrics output to the numbers M1.3 ratchets.

    Length metrics exclude the named generated modules; smell counters sum
    every module, because the ticket's baselines (ptr_len 916, i32 1,689,
    c_str 6,763) are whole-tree figures.
    """
    gen = set(generated_modules)
    files = data.get("files", [])
    fns = data.get("functions", [])

    hand_files = [f for f in files if _stem(f["file"]) not in gen]
    hand_fns = [f for f in fns if _stem(f["file"]) not in gen]

    long_fns = {
        f"{_stem(f['file'])}::{f['name']}": f["sloc"]
        for f in hand_fns
        if f["sloc"] > FN_SLOC_LIMIT
    }
    large_files = {
        _stem(f["file"]): f["sloc"] for f in hand_files if f["sloc"] > FILE_SLOC_LIMIT
    }
    smells: dict[str, int] = {}
    for f in files:
        for key, value in f.get("smells", {}).items():
            smells[key] = smells.get(key, 0) + value

    names = sorted(set(cycle_module_names))
    return {
        "generated_modules": list(generated_modules),
        "limits": {"fn_sloc": FN_SLOC_LIMIT, "file_sloc": FILE_SLOC_LIMIT},
        "scalars": {
            "hand_fns_over_sloc_limit": len(long_fns),
            "hand_files_over_sloc_limit": len(large_files),
            "ptr_len_param_pair": smells.get("ptr_len_param_pair", 0),
            "i32_as_bool": smells.get("i32_as_bool", 0),
            "cstr_literal": smells.get("cstr_literal", 0),
            "fixed_u8_buffer": smells.get("fixed_u8_buffer", 0),
            "cycle_sccs": cycle_sccs,
            "cycle_modules": len(names),
        },
        "long_fns": dict(sorted(long_fns.items())),
        "large_files": dict(sorted(large_files.items())),
        "cycle_module_names": names,
    }


def measure(
    src: Path = DEFAULT_SRC,
    *,
    metrics_py: Path = DEFAULT_METRICS,
    generated_modules: tuple[str, ...] = GENERATED_MODULES,
) -> dict:
    data = load_metrics(src, metrics_py)
    mods = ritz1_arch.scan(src)
    cyc = ritz1_arch.cycles(mods)
    names = sorted({m for component in cyc for m in component})
    return summarise(
        data,
        generated_modules=generated_modules,
        cycle_sccs=len(cyc),
        cycle_module_names=names,
    )


def load_baseline(path: Path = DEFAULT_BASELINE) -> dict:
    return json.loads(path.read_text())


def dump_baseline(measured: dict, path: Path, previous: dict | None = None) -> None:
    """Write `measured`, keeping provenance/notes from the old baseline."""
    doc = dict(previous or {})
    doc.update(measured)
    path.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")


def compare(measured: dict, baseline: dict) -> list[Finding]:
    """Every place the tree moved against the baseline.

    Regressions are failures; improvements are reported so the operator can
    run `--update`.  Equal metrics produce nothing.
    """
    out: list[Finding] = []
    base_scalars = baseline.get("scalars", {})
    meas_scalars = measured.get("scalars", {})
    for name in SCALARS:
        b = base_scalars.get(name)
        m = meas_scalars.get(name)
        if b is None or m is None or b == m:
            continue
        if m > b:
            out.append(
                Finding(
                    "regression",
                    name,
                    b,
                    m,
                    f"{name} regressed: baseline {b}, measured {m}",
                )
            )
        else:
            out.append(
                Finding(
                    "improvement",
                    name,
                    b,
                    m,
                    f"{name} improved: baseline {b}, measured {m}; "
                    "run with --update to record it",
                )
            )

    def _maps(key: str, unit: str) -> None:
        b_map = baseline.get(key, {})
        m_map = measured.get(key, {})
        for item in sorted(set(b_map) | set(m_map)):
            b, m = b_map.get(item), m_map.get(item)
            if m is None:
                out.append(
                    Finding(
                        "improvement",
                        item,
                        b,
                        None,
                        f"{item} is now at most {unit}; run with --update to record it",
                    )
                )
            elif b is None:
                out.append(
                    Finding(
                        "regression",
                        item,
                        None,
                        m,
                        f"{item} is {m} {unit} and the baseline had no such entry",
                    )
                )
            elif m > b:
                out.append(
                    Finding(
                        "regression",
                        item,
                        b,
                        m,
                        f"{item} grew: baseline {b}, measured {m}",
                    )
                )
            elif m < b:
                out.append(
                    Finding(
                        "improvement",
                        item,
                        b,
                        m,
                        f"{item} improved: baseline {b}, measured {m}; "
                        "run with --update to record it",
                    )
                )

    _maps("long_fns", "SLOC")
    _maps("large_files", "SLOC")

    base_cycle = set(baseline.get("cycle_module_names", []))
    meas_cycle = set(measured.get("cycle_module_names", []))
    for name in sorted(meas_cycle - base_cycle):
        out.append(
            Finding(
                "regression",
                name,
                sorted(base_cycle),
                sorted(meas_cycle),
                f"`{name}` joined an import cycle (baseline cycle: "
                + (", ".join(sorted(base_cycle)) or "none")
                + ")",
            )
        )
    for name in sorted(base_cycle - meas_cycle):
        out.append(
            Finding(
                "improvement",
                name,
                sorted(base_cycle),
                sorted(meas_cycle),
                f"`{name}` left the import cycle; run with --update to record it",
            )
        )
    return out


def _report(findings: list[Finding]) -> None:
    for finding in findings:
        prefix = "FAIL" if finding.kind == "regression" else "NOTE"
        print(f"{prefix}: {finding.detail}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument(
        "--metrics",
        type=Path,
        default=DEFAULT_METRICS,
        help="ritz_metrics.py to run (default: projects/larb/tools/ritz-metrics)",
    )
    ap.add_argument(
        "--baseline", type=Path, default=DEFAULT_BASELINE, help="committed baseline"
    )
    ap.add_argument(
        "--measured",
        type=Path,
        help="compare a saved measurement instead of scanning --src",
    )
    ap.add_argument(
        "--update",
        action="store_true",
        help="record the measured values (including improvements) in the baseline",
    )
    args = ap.parse_args(argv)

    baseline = load_baseline(args.baseline)
    # The committed file is the authority on which modules are generated.
    generated = tuple(baseline.get("generated_modules", DEFAULT_GENERATED))
    if args.measured:
        measured = json.loads(args.measured.read_text())
    else:
        measured = measure(
            args.src, metrics_py=args.metrics, generated_modules=generated
        )
    findings = compare(measured, baseline)
    _report(findings)

    regressions = [f for f in findings if f.kind == "regression"]
    if regressions:
        print(
            f"{len(regressions)} regression(s) against {args.baseline}",
            file=sys.stderr,
        )
        return 1
    if args.update:
        dump_baseline(measured, args.baseline, baseline)
        print(f"recorded {len(findings)} change(s) in {args.baseline}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
