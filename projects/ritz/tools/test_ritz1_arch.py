"""Tests for tools/ritz1_arch.py (AGAST #1827, #3896).

`make arch-report` prints this script's measurements; ARCHITECTURE.md commits
none of them (#3896: a committed block made every ritz1 sema commit conflict
with every other).  The counting rules are pinned below, and so are the
invariants `--check` holds the doc and ritz1/src to.
"""

import os
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent))

from ritz1_arch import (
    CYCLE_BASELINE,
    DEFAULT_SRC,
    cycles,
    doc_entries,
    render,
    scan,
    violations,
)

pytestmark = pytest.mark.unit

TOOL = Path(__file__).with_name("ritz1_arch.py")


def _fresh(tmp_path):
    d = tmp_path / "fresh"
    d.mkdir()
    return d


def src(tmp_path, files):
    for name, text in files.items():
        (tmp_path / f"{name}.ritz").write_text(text)
    return scan(tmp_path)


def test_counts_lines_and_code_lines(tmp_path):
    mods = src(tmp_path, {"a": "# header\n\nfn f()\n    # note\n    return\n"})
    a = mods["a"]
    assert a.lines == 5
    assert a.code == 2  # comments and blank lines are not code


def test_splits_local_and_ritzlib_imports(tmp_path):
    mods = src(
        tmp_path,
        {
            "a": "import ritzlib.sys\nimport ritzlib.os.env\nimport b   # why\npub import c\n",
            "b": "",
            "c": "",
        },
    )
    assert mods["a"].imports == ["b", "c"]
    assert mods["a"].ritzlib == ["os.env", "sys"]


def test_commented_import_is_not_an_import(tmp_path):
    mods = src(
        tmp_path,
        {"a": "    # import b\n# import b\nstruct S\n  imports: *u8\n", "b": ""},
    )
    assert mods["a"].imports == []


def test_import_of_unknown_module_is_ignored(tmp_path):
    # Not in src/ and not ritzlib: resolved elsewhere (RITZ_PATH), not an edge.
    mods = src(tmp_path, {"a": "import elsewhere\n"})
    assert mods["a"].imports == []


def test_generated_header_marks_module(tmp_path):
    mods = src(tmp_path, {"g": "# Generated by ritzgen - x\n", "h": "# handwritten\n"})
    assert mods["g"].generated and not mods["h"].generated


def test_function_length_is_code_lines_to_dedent(tmp_path):
    text = (
        "fn small()\n"
        "    return\n"
        "\n"
        "pub fn big(x: i32) -> i32\n"
        "    var y = x\n"
        "    # comment\n"
        "\n"
        "    if y > 0\n"
        "        y = 1\n"
        "    return y\n"
        "impl S\n"
        "    fn m(self: *S)\n"
        "        a()\n"
        "        b()\n"
        "    fn n(self: *S)\n"
        "        c()\n"
    )
    fns = {f.name: f.code for f in src(tmp_path, {"a": text})["a"].fns}
    assert fns == {"small": 2, "big": 5, "m": 3, "n": 2}


def test_cycles_finds_only_multi_module_components(tmp_path):
    mods = src(
        tmp_path,
        {
            "a": "import b\n",
            "b": "import c\n",
            "c": "import a\n",
            "d": "import a\n",
            "e": "import e\n",  # self-import is not a cycle we report
        },
    )
    assert cycles(mods) == [["a", "b", "c"]]
    assert mods["e"].imports == []


def test_render_reports_totals_and_graph(tmp_path):
    mods = src(
        tmp_path,
        {
            "main": "import lib\nimport ritzlib.io\nfn main()\n    run()\n",
            "lib": "# Generated by ritzgen\nfn run()\n    x()\n",
        },
    )
    out = render(mods, long_fn=1)
    assert "**2** modules" in out
    assert "**7** lines" in out
    # | module | imported by | lines | code lines | local imports |
    assert "| `main` | 0 | 4 | 4 | lib |" in out
    assert "| `lib` (gen) | 1 | 3 | 2 | — |" in out
    assert "`io` (1)" in out
    assert "No import cycles" in out
    assert "2 functions longer than 1 code lines" in out


def test_render_rows_follow_dependency_order(tmp_path):
    mods = src(tmp_path, {"a": "import b\n", "b": "import c\n", "c": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["c", "b", "a"]


def test_render_breaks_order_ties_alphabetically(tmp_path):
    mods = src(tmp_path, {"x": "import z\n", "y": "", "z": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["y", "z", "x"]
    mods = src(_fresh(tmp_path), {"a": "", "b": "import c\n", "c": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["a", "c", "b"]


def test_render_lists_cycle_members(tmp_path):
    mods = src(tmp_path, {"a": "import b\n", "b": "import a\n"})
    assert "1 import cycle" in render(mods)
    assert "`a` ↔ `b`" in render(mods)


def test_render_says_where_each_check_runs(tmp_path):
    mods = src(
        tmp_path,
        {
            "a": "pub fn a_check(sm: *Sema, e: *Expr)\n    x()\n",
            "b": "pub fn b_check(s: *EmitterState, e: *Expr)\n    x()\n",
        },
    )
    assert mods["a"].sema_checks == ["a_check"] and not mods["a"].emitter_checks
    assert mods["b"].emitter_checks == ["b_check"] and not mods["b"].sema_checks
    out = render(mods)
    assert "| `a` | Sema |" in out and "| `b` | emitter |" in out


# --- `--check`: the invariants (#3896) -------------------------------------

DOC = """# x

## Module responsibilities

| Module | Responsibility |
|---|---|
| `main`, `sema` | Driver. |

**Checks**

- `a_check` — rule a.

- `b_check` — rule b,
  over two lines.

## Build
"""

SRC = {
    "main": "import sema\n",
    "sema": "",
    "a_check": "import sema\npub fn a_check(sm: *Sema, e: *Expr)\n    x()\n",
    "b_check": "pub fn b_check(s: *EmitterState, e: *Expr)\n    x()\n",
}


def check(tmp_path, files=SRC, doc=DOC, baseline=frozenset()):
    return violations(src(tmp_path, files), doc, baseline)


def test_doc_entries_reads_tables_and_the_checks_list():
    documented, checks = doc_entries(DOC)
    assert documented == {"main", "sema", "a_check", "b_check"}
    assert checks == ["a_check", "b_check"]


def test_invariants_hold_for_a_consistent_doc(tmp_path):
    assert check(tmp_path) == []


def test_undocumented_module_fails(tmp_path):
    out = check(tmp_path, {**SRC, "new_mod": ""})
    assert len(out) == 1 and "new_mod" in out[0]


def test_documented_module_that_is_gone_fails(tmp_path):
    files = {k: v for k, v in SRC.items() if k != "b_check"}
    out = check(tmp_path, files)
    assert len(out) == 1 and "b_check" in out[0]


def test_sema_check_listed_outside_checks_fails(tmp_path):
    doc = DOC.replace("`main`, `sema`", "`main`, `sema`, `c_check`")
    files = {**SRC, "c_check": "pub fn c_check(sm: *Sema)\n    x()\n"}
    out = check(tmp_path, files, doc)
    assert len(out) == 1 and "c_check" in out[0] and "Checks" in out[0]


def test_unsorted_checks_list_fails(tmp_path):
    doc = DOC.replace("- `a_check` — rule a.\n\n", "").replace(
        "  over two lines.\n", "  over two lines.\n\n- `a_check` — rule a.\n"
    )
    out = check(tmp_path, doc=doc)
    assert len(out) == 1 and "sorted" in out[0]


def test_checks_entries_need_a_blank_line_between(tmp_path):
    # Two rooms editing neighbouring entries must not touch adjacent lines.
    doc = DOC.replace("rule a.\n\n- `b_check`", "rule a.\n- `b_check`")
    out = check(tmp_path, doc=doc)
    assert len(out) == 1 and "blank line" in out[0]


def test_module_joining_an_import_cycle_fails(tmp_path):
    files = {**SRC, "sema": "import a_check\n"}  # a_check <-> sema
    out = check(tmp_path, files, baseline=frozenset({"sema"}))
    assert len(out) == 1 and "a_check" in out[0] and "cycle" in out[0]
    assert check(tmp_path, files, baseline=frozenset({"sema", "a_check"})) == []


def test_committed_measurements_fail(tmp_path):
    doc = DOC + "<!-- BEGIN generated by tools/ritz1_arch.py -->\n"
    out = check(tmp_path, doc=doc)
    assert len(out) == 1 and "arch-report" in out[0]


def test_check_cli_exit_codes(tmp_path):
    (tmp_path / "src").mkdir()
    for name, text in SRC.items():
        (tmp_path / "src" / f"{name}.ritz").write_text(text)
    doc = tmp_path / "ARCH.md"
    run = [
        sys.executable,
        str(TOOL),
        "--src",
        str(tmp_path / "src"),
        "--check",
        str(doc),
    ]
    doc.write_text(DOC)
    assert subprocess.run(run, capture_output=True, check=False).returncode == 0
    doc.write_text(DOC.replace("- `a_check` — rule a.\n\n", ""))
    bad = subprocess.run(run, capture_output=True, text=True, check=False)
    assert bad.returncode == 1 and "a_check" in bad.stderr


def test_the_real_doc_holds_the_invariants():
    # The gate's check (tools-unit): ritz1/ARCHITECTURE.md against ritz1/src.
    doc = (DEFAULT_SRC.parent / "ARCHITECTURE.md").read_text()
    assert violations(scan(DEFAULT_SRC), doc, CYCLE_BASELINE) == []


# --- acceptance: two sema rooms cherry-pick onto each other (#3896) --------


def _git(repo, *args):
    # HOME and no system config: the user's git config (signing, hooks) stays out.
    env = {
        **os.environ,
        "HOME": str(repo),
        "GIT_CONFIG_NOSYSTEM": "1",
        "GIT_AUTHOR_NAME": "t",
        "GIT_AUTHOR_EMAIL": "t@t",
        "GIT_COMMITTER_NAME": "t",
        "GIT_COMMITTER_EMAIL": "t@t",
    }
    subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True, env=env
    )


def _entry_end(lines, name):
    i = next(i for i, ln in enumerate(lines) if ln.startswith(f"- `{name}`"))
    while lines[i + 1].strip():
        i += 1
    return i


def _room(repo, branch, new=None, after=None, edit=None):
    """A sema room on `branch` off `base`: optionally a new Sema check module
    `new` with its Checks entry after `after`'s, and optionally a note on
    the existing entry `edit`, as a move off the emitter adds."""
    _git(repo, "checkout", "-q", "-b", branch, "base")
    doc = repo / "ARCHITECTURE.md"
    lines = doc.read_text().split("\n")
    if edit:
        lines[_entry_end(lines, edit)] += f" Moved to Sema by {branch}."
    if new:
        (repo / "src" / f"{new}.ritz").write_text(
            f"import sema\npub fn {new}(sm: *Sema, e: *Expr)\n    x()\n"
        )
        i = _entry_end(lines, after)
        lines[i + 1 : i + 1] = ["", f"- `{new}` — rule {new}."]
    doc.write_text("\n".join(lines))
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", branch)


@pytest.fixture
def repo(tmp_path):
    """ritz1/src and ARCHITECTURE.md as committed, in a scratch repo."""
    repo = tmp_path / "repo"
    (repo / "src").mkdir(parents=True)
    for f in DEFAULT_SRC.glob("*.ritz"):
        (repo / "src" / f.name).write_bytes(f.read_bytes())
    doc = (DEFAULT_SRC.parent / "ARCHITECTURE.md").read_text()
    (repo / "ARCHITECTURE.md").write_text(doc)
    _git(repo, "init", "-q", "-b", "base")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "base")
    return repo, doc_entries(doc)[1]


def _cross_pick(repo):
    for onto, pick in (("a", "b"), ("b", "a")):
        _git(repo, "checkout", "-q", "-B", f"{onto}-{pick}", onto)
        _git(repo, "cherry-pick", pick)  # check=True: a conflict fails here
        doc = (repo / "ARCHITECTURE.md").read_text()
        assert violations(scan(repo / "src"), doc, CYCLE_BASELINE) == []


def test_two_moves_on_neighbouring_checks_cherry_pick(repo):
    # #1816's usual room: note its own (neighbouring) entry.
    repo, checks = repo
    _room(repo, "a", edit=checks[3])
    _room(repo, "b", edit=checks[4])
    _cross_pick(repo)


def test_two_new_checks_in_neighbouring_gaps_cherry_pick(repo):
    repo, checks = repo
    _room(repo, "a", new=checks[3] + "_x", after=checks[3], edit=checks[0])
    _room(repo, "b", new=checks[4] + "_x", after=checks[4], edit=checks[7])
    _cross_pick(repo)
