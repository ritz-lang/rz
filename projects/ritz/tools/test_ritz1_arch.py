"""Tests for tools/ritz1_arch.py (AGAST #1827).

ritz1/ARCHITECTURE.md embeds this script's output; every number in that doc
comes from here, so the counting rules are pinned below.
"""

import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent))

from ritz1_arch import (
    BEGIN,
    END,
    cycles,
    render,
    replace_block,
    scan,
)

pytestmark = pytest.mark.unit

TOOL = Path(__file__).with_name("ritz1_arch.py")


def _fresh(tmp_path):
    d = tmp_path / "fresh"
    d.mkdir()
    return d


def src(tmp_path, files):
    for name, text in files.items():
        (tmp_path / f"{name}.ritz").write_text(text)
    return scan(tmp_path)


def test_counts_lines_and_code_lines(tmp_path):
    mods = src(tmp_path, {"a": "# header\n\nfn f()\n    # note\n    return\n"})
    a = mods["a"]
    assert a.lines == 5
    assert a.code == 2  # comments and blank lines are not code


def test_splits_local_and_ritzlib_imports(tmp_path):
    mods = src(
        tmp_path,
        {
            "a": "import ritzlib.sys\nimport ritzlib.os.env\nimport b   # why\npub import c\n",
            "b": "",
            "c": "",
        },
    )
    assert mods["a"].imports == ["b", "c"]
    assert mods["a"].ritzlib == ["os.env", "sys"]


def test_commented_import_is_not_an_import(tmp_path):
    mods = src(
        tmp_path,
        {"a": "    # import b\n# import b\nstruct S\n  imports: *u8\n", "b": ""},
    )
    assert mods["a"].imports == []


def test_import_of_unknown_module_is_ignored(tmp_path):
    # Not in src/ and not ritzlib: resolved elsewhere (RITZ_PATH), not an edge.
    mods = src(tmp_path, {"a": "import elsewhere\n"})
    assert mods["a"].imports == []


def test_generated_header_marks_module(tmp_path):
    mods = src(tmp_path, {"g": "# Generated by ritzgen - x\n", "h": "# handwritten\n"})
    assert mods["g"].generated and not mods["h"].generated


def test_function_length_is_code_lines_to_dedent(tmp_path):
    text = (
        "fn small()\n"
        "    return\n"
        "\n"
        "pub fn big(x: i32) -> i32\n"
        "    var y = x\n"
        "    # comment\n"
        "\n"
        "    if y > 0\n"
        "        y = 1\n"
        "    return y\n"
        "impl S\n"
        "    fn m(self: *S)\n"
        "        a()\n"
        "        b()\n"
        "    fn n(self: *S)\n"
        "        c()\n"
    )
    fns = {f.name: f.code for f in src(tmp_path, {"a": text})["a"].fns}
    assert fns == {"small": 2, "big": 5, "m": 3, "n": 2}


def test_cycles_finds_only_multi_module_components(tmp_path):
    mods = src(
        tmp_path,
        {
            "a": "import b\n",
            "b": "import c\n",
            "c": "import a\n",
            "d": "import a\n",
            "e": "import e\n",  # self-import is not a cycle we report
        },
    )
    assert cycles(mods) == [["a", "b", "c"]]
    assert mods["e"].imports == []


def test_render_reports_totals_and_graph(tmp_path):
    mods = src(
        tmp_path,
        {
            "main": "import lib\nimport ritzlib.io\nfn main()\n    run()\n",
            "lib": "# Generated by ritzgen\nfn run()\n    x()\n",
        },
    )
    out = render(mods, long_fn=1)
    assert out.startswith(BEGIN) and out.rstrip().endswith(END)
    assert "**2** modules" in out
    assert "**7** lines" in out
    # | module | imported by | lines | code lines | local imports |
    assert "| `main` | 0 | 4 | 4 | lib |" in out
    assert "| `lib` (gen) | 1 | 3 | 2 | — |" in out
    assert "`io` (1)" in out
    assert "No import cycles" in out
    assert "2 functions longer than 1 code lines" in out


def test_render_rows_follow_dependency_order(tmp_path):
    mods = src(tmp_path, {"a": "import b\n", "b": "import c\n", "c": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["c", "b", "a"]


def test_render_breaks_order_ties_alphabetically(tmp_path):
    mods = src(tmp_path, {"x": "import z\n", "y": "", "z": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["y", "z", "x"]
    mods = src(_fresh(tmp_path), {"a": "", "b": "import c\n", "c": ""})
    rows = [ln for ln in render(mods).splitlines() if ln.startswith("| `")]
    assert [r.split("`")[1] for r in rows] == ["a", "c", "b"]


def test_render_lists_cycle_members(tmp_path):
    mods = src(tmp_path, {"a": "import b\n", "b": "import a\n"})
    assert "1 import cycle" in render(mods)
    assert "`a` ↔ `b`" in render(mods)


def test_replace_block_is_idempotent_and_needs_markers():
    doc = f"intro\n{BEGIN}\nold\n{END}\noutro\n"
    new = replace_block(doc, f"{BEGIN}\nnew\n{END}\n")
    assert new == f"intro\n{BEGIN}\nnew\n{END}\noutro\n"
    assert replace_block(new, f"{BEGIN}\nnew\n{END}\n") == new
    with pytest.raises(ValueError):
        replace_block("no markers\n", f"{BEGIN}\nx\n{END}\n")


def test_check_flags_a_stale_doc(tmp_path):
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "a.ritz").write_text("fn f()\n    g()\n")
    doc = tmp_path / "ARCH.md"
    doc.write_text(f"{BEGIN}\nstale\n{END}\n")
    run = [sys.executable, str(TOOL), "--src", str(tmp_path / "src")]
    assert (
        subprocess.run(
            [*run, "--check", str(doc)], capture_output=True, check=False
        ).returncode
        == 1
    )
    assert (
        subprocess.run(
            [*run, "--write", str(doc)], capture_output=True, check=False
        ).returncode
        == 0
    )
    assert (
        subprocess.run(
            [*run, "--check", str(doc)], capture_output=True, check=False
        ).returncode
        == 0
    )
