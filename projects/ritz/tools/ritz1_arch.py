#!/usr/bin/env python3
"""Measure ritz1/src, and check ritz1/ARCHITECTURE.md's invariants.

    ritz1_arch.py                    # the measurements (make arch-report)
    ritz1_arch.py --check DOC        # exit 1 if an invariant below fails
    ritz1_arch.py --src DIR ...      # measure DIR instead of ritz1/src

ARCHITECTURE.md states no counts (AGAST #1827: the hand-written doc said
"11 files, ~13,700 lines" for two years while the compiler grew past 70k),
and since #3896 it embeds none either: a committed measurement block changed
with every ritz1 commit, so every pair of #1816 sema rooms conflicted on it.
The numbers are printed on demand; the gate checks only what must not drift
(`violations`, run by tools/test_ritz1_arch.py in `make tools-unit`):

- every module in ritz1/src has an entry under "## Module responsibilities",
  and every entry names a module that exists;
- every module with a `pub fn *check*(sm: *Sema` is in the **Checks** list;
- the Checks list is sorted, one entry per check, a blank line between
  entries (two rooms editing neighbouring entries touch no adjacent lines,
  so git merges them);
- no module joins an import cycle: cycle members stay within
  CYCLE_BASELINE (#1818 shrinks it; nothing may grow it);
- no measurement block is committed.

The emitter-check allowlist only shrinking is
tools/test_ritz1_emitter_check_freeze.py's job, not this script's.

Counting rules (pinned by test_ritz1_arch.py):
- lines: physical lines.  code: lines that are neither blank nor `#` comments.
- an import is any `import X` / `pub import X` line, as ritz1/mkdeps.py reads
  them.  `ritzlib.*` imports are listed separately; a name that is not a module in src/ and not ritzlib is not
  an edge (it resolves through RITZ_PATH).  Self-imports are dropped.
- a module is generated when its first line starts `# Generated by ritzgen`.
- a function runs from its `fn` line to the next code line indented no deeper
  than the `fn`; its length is the code lines in that span.
- a cycle is a strongly connected component of the import graph with more than
  one module.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

LONG_FN = 300
DEFAULT_SRC = Path(__file__).resolve().parent.parent / "ritz1" / "src"
# The block this script used to write into the doc, before #3896.
OLD_BLOCK = "<!-- BEGIN generated by tools/ritz1_arch.py -->"

# The modules in ritz1's one import cycle at #3896: emitter_core's
# EmitterState and everything that reaches it both ways.  A module may leave
# the cycle (#1818's work; delete it here then, or don't: a subset passes),
# but none may join it.
CYCLE_BASELINE = frozenset(
    (
        "binder_check",
        "bool_check",
        "bool_kind",
        "deref_field",
        "emitter_asm",
        "emitter_core",
        "emitter_expr",
        "emitter_expr_access",
        "emitter_expr_arith",
        "emitter_expr_call",
        "emitter_match",
        "emitter_print",
        "emitter_stmt",
        "float_slot",
        "index_through",
        "let_check",
        "literal_slot",
        "monomorph",
        "narrowing",
        "ownership",
        "ref_check",
        "sema",
        "sema_probe",
        "sema_type",
        "tail_value",
    )
)

IMPORT_RE = re.compile(r"^[ \t]*(?:pub[ \t]+)?import[ \t]+([A-Za-z_][\w.]*)")
FN_RE = re.compile(r"^([ \t]*)(?:pub[ \t]+)?fn[ \t]+([A-Za-z_]\w*)")
# As tools/test_ritz1_emitter_check_freeze.py greps, on either side.
CHECK_RE = re.compile(
    r"^pub fn ([a-z_]*check[a-z_]*)\((sm: \*Sema|s: \*EmitterState)\b"
)


@dataclass
class Fn:
    name: str
    line: int
    code: int


@dataclass
class Module:
    name: str
    lines: int = 0
    code: int = 0
    generated: bool = False
    imports: list[str] = field(default_factory=list)
    ritzlib: list[str] = field(default_factory=list)
    fns: list[Fn] = field(default_factory=list)
    sema_checks: list[str] = field(default_factory=list)
    emitter_checks: list[str] = field(default_factory=list)


def _is_code(line: str) -> bool:
    s = line.strip()
    return bool(s) and not s.startswith("#")


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" \t"))


def _functions(lines: list[str]) -> list[Fn]:
    fns: list[Fn] = []
    for i, line in enumerate(lines):
        m = FN_RE.match(line)
        if not m:
            continue
        depth, code = len(m.group(1)), 1
        for body in lines[i + 1 :]:
            if not _is_code(body):
                continue
            if _indent(body) <= depth:
                break
            code += 1
        fns.append(Fn(m.group(2), i + 1, code))
    return fns


def scan(src: Path) -> dict[str, Module]:
    """Measure every `*.ritz` directly in `src`."""
    files = sorted(src.glob("*.ritz"))
    names = {f.stem for f in files}
    mods: dict[str, Module] = {}
    for f in files:
        lines = f.read_text(errors="replace").splitlines()
        mod = Module(f.stem, lines=len(lines))
        mod.code = sum(1 for ln in lines if _is_code(ln))
        mod.generated = bool(lines) and lines[0].startswith("# Generated by ritzgen")
        local, lib = set(), set()
        for ln in lines:
            m = IMPORT_RE.match(ln)
            if not m:
                continue
            name = m.group(1)
            if name.startswith("ritzlib."):
                lib.add(name[len("ritzlib.") :])
            elif name in names and name != mod.name:
                local.add(name)
        mod.imports, mod.ritzlib = sorted(local), sorted(lib)
        mod.fns = _functions(lines)
        for ln in lines:
            m = CHECK_RE.match(ln)
            if m:
                side = (
                    mod.sema_checks
                    if m.group(2).startswith("sm")
                    else mod.emitter_checks
                )
                side.append(m.group(1))
        mods[mod.name] = mod
    return mods


def _sccs(mods: dict[str, Module]) -> list[list[str]]:
    """Tarjan's algorithm; each component sorted, dependencies first."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    stack: list[str] = []
    on: set[str] = set()
    out: list[list[str]] = []

    def visit(v: str) -> None:
        index[v] = low[v] = len(index)
        stack.append(v)
        on.add(v)
        for w in mods[v].imports:
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp))

    sys.setrecursionlimit(max(1000, 10 * len(mods)))
    for v in sorted(mods):
        if v not in index:
            visit(v)
    return out


def cycles(mods: dict[str, Module]) -> list[list[str]]:
    return sorted(c for c in _sccs(mods) if len(c) > 1)


def dep_order(mods: dict[str, Module]) -> list[str]:
    """Modules with every import before its importer; ties alphabetical."""
    comps = _sccs(mods)
    owner = {m: i for i, c in enumerate(comps) for m in c}
    deps = {
        i: {owner[d] for m in c for d in mods[m].imports} - {i}
        for i, c in enumerate(comps)
    }
    done: set[int] = set()
    order: list[str] = []
    while len(done) < len(comps):
        ready = [i for i in deps if i not in done and deps[i] <= done]
        nxt = min(ready, key=lambda i: comps[i][0])
        done.add(nxt)
        order += comps[nxt]
    return order


def render(mods: dict[str, Module], long_fn: int = LONG_FN) -> str:
    importers = {m: sum(m in x.imports for x in mods.values()) for m in mods}
    gen = [m for m in sorted(mods) if mods[m].generated]
    total = sum(m.lines for m in mods.values())
    code = sum(m.code for m in mods.values())
    gen_lines = sum(mods[m].lines for m in gen)
    fns = [(f, m) for m in mods.values() for f in m.fns]
    long = sorted(
        ((f, m) for f, m in fns if f.code > long_fn),
        key=lambda p: (-p[0].code, p[1].name),
    )
    cyc = cycles(mods)
    edges = sum(len(m.imports) for m in mods.values())

    o = []
    o.append(
        f"`ritz1/src/` has **{len(mods)}** modules, **{total}** lines "
        f"(**{code}** code lines, excluding blanks and comments), "
        f"**{len(fns)}** functions and **{edges}** local import edges. "
        f"{len(gen)} modules ({gen_lines} lines) are generated by ritzgen: "
        + (", ".join(f"`{m}`" for m in gen) or "none")
        + "."
    )
    o += ["", "### Modules in dependency order", ""]
    o.append(
        "Every module appears after all the modules it imports (modules in a cycle are adjacent). "
        "`(gen)` marks generated modules."
    )
    o += [
        "",
        "| Module | Imported by | Lines | Code | Local imports |",
        "|---|--:|--:|--:|---|",
    ]
    for name in dep_order(mods):
        m = mods[name]
        label = f"`{name}`" + (" (gen)" if m.generated else "")
        imps = ", ".join(m.imports) or "—"
        o.append(f"| {label} | {importers[name]} | {m.lines} | {m.code} | {imps} |")

    o += ["", "### Import cycles", ""]
    if not cyc:
        o.append("No import cycles.")
    else:
        o.append(
            f"{len(cyc)} import cycle{'s' if len(cyc) != 1 else ''} "
            "(strongly connected components of more than one module):"
        )
        o.append("")
        for c in cyc:
            o.append(f"- {len(c)} modules: " + " ↔ ".join(f"`{m}`" for m in c))

    users: dict[str, int] = {}
    for m in mods.values():
        for lib in m.ritzlib:
            users[lib] = users.get(lib, 0) + 1
    o += ["", "### ritzlib modules imported", ""]
    o.append(
        f"{len(users)} ritzlib modules, each with the number of ritz1 modules importing it: "
        + (", ".join(f"`{k}` ({v})" for k, v in sorted(users.items())) or "none")
        + "."
    )

    o += ["", "### Checks", ""]
    o.append(
        "Where each module's `pub fn *check*` fns run (`sm: *Sema` or `s: *EmitterState`):"
    )
    o += ["", "| Module | Runs on |", "|---|---|"]
    for name in sorted(mods):
        m = mods[name]
        sides = [
            s
            for s, fs in (("Sema", m.sema_checks), ("emitter", m.emitter_checks))
            if fs
        ]
        if sides:
            o.append(f"| `{name}` | {' + '.join(sides)} |")

    o += ["", "### Long functions", ""]
    o.append(f"{len(long)} functions longer than {long_fn} code lines:")
    if long:
        o += ["", "| Function | Module:line | Code lines |", "|---|---|--:|"]
        o += [f"| `{f.name}` | `{m.name}:{f.line}` | {f.code} |" for f, m in long]
    o.append("")
    return "\n".join(o)


_LEAD_RE = re.compile(r"^(?:\| |- )((?:`[a-z_0-9]+`(?:, )?)+)")


def doc_entries(doc: str) -> tuple[set[str], list[str]]:
    """(every module named by an entry under "## Module responsibilities",
    the **Checks** list's modules in doc order).  An entry is a table row or
    a `- ` item whose first cell / text starts with backticked names."""
    documented: set[str] = set()
    checks: list[str] = []
    inside = in_checks = False
    for ln in doc.splitlines():
        if ln.startswith("#"):
            inside = ln.strip() == "## Module responsibilities"
            in_checks = False
            continue
        if not inside:
            continue
        if ln.startswith("**"):
            in_checks = ln.strip() == "**Checks**"
            continue
        m = _LEAD_RE.match(ln)
        if m:
            names = re.findall(r"`([a-z_0-9]+)`", m.group(1))
            documented.update(names)
            if in_checks and ln.startswith("- "):
                checks += names
    return documented, checks


def _checks_spacing(doc: str) -> list[str]:
    """Checks entries not preceded by a blank line (except the first)."""
    out, in_checks, prev = [], False, ""
    for ln in doc.splitlines():
        if ln.startswith(("#", "**")):
            in_checks = ln.strip() == "**Checks**"
            first = True
        elif in_checks and ln.startswith("- "):
            if not first and prev.strip():
                out.append(ln.split("`")[1] if "`" in ln else ln)
            first = False
        prev = ln
    return out


def violations(
    mods: dict[str, Module], doc: str, baseline: frozenset[str] = CYCLE_BASELINE
) -> list[str]:
    """One message per broken invariant (see the module docstring)."""
    documented, checks = doc_entries(doc)
    out = [
        f"module `{m}` has no entry under 'Module responsibilities'"
        for m in sorted(set(mods) - documented)
    ]
    out += [
        f"'Module responsibilities' names `{m}`, which is not in ritz1/src"
        for m in sorted(documented - set(mods))
    ]
    out += [
        f"`{m}` has a Sema check: give it an entry in the **Checks** list"
        for m in sorted(mods)
        if mods[m].sema_checks and m not in checks
    ]
    if checks != sorted(checks):
        out.append("the **Checks** list is not sorted: " + ", ".join(checks))
    out += [
        f"Checks entry `{m}` needs a blank line before it (neighbouring "
        "entries must not touch adjacent lines)"
        for m in _checks_spacing(doc)
    ]
    joined = sorted({m for c in cycles(mods) for m in c} - baseline)
    if joined:
        out.append(
            "joined an import cycle (see CYCLE_BASELINE in "
            "tools/ritz1_arch.py): " + ", ".join(f"`{m}`" for m in joined)
        )
    if OLD_BLOCK in doc:
        out.append(
            "the doc commits measurements: delete the block; "
            "`make arch-report` prints them"
        )
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--long-fn", type=int, default=LONG_FN)
    ap.add_argument("--check", type=Path, metavar="DOC")
    args = ap.parse_args(argv)

    mods = scan(args.src)
    if args.check:
        bad = violations(mods, args.check.read_text())
        for msg in bad:
            print(f"{args.check}: {msg}", file=sys.stderr)
        return 1 if bad else 0
    sys.stdout.write(render(mods, args.long_fn))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
