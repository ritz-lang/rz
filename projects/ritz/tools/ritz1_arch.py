#!/usr/bin/env python3
"""Measure ritz1/src and render the generated part of ritz1/ARCHITECTURE.md.

    ritz1_arch.py                    # print the block to stdout
    ritz1_arch.py --write DOC        # replace the block in DOC
    ritz1_arch.py --check DOC        # exit 1 if DOC's block is stale
    ritz1_arch.py --src DIR ...      # measure DIR instead of ritz1/src

Every number in ARCHITECTURE.md comes from here (AGAST #1827): the previous
hand-written doc said "11 files, ~13,700 lines" for two years while the
compiler grew past 70k.  Regenerate rather than edit the block by hand.

Counting rules (pinned by test_ritz1_arch.py):
- lines: physical lines.  code: lines that are neither blank nor `#` comments.
- an import is any `import X` / `pub import X` line, as ritz1/mkdeps.py reads
  them.  `ritzlib.*` imports are listed separately; a name that is not a module in src/ and not ritzlib is not
  an edge (it resolves through RITZ_PATH).  Self-imports are dropped.
- a module is generated when its first line starts `# Generated by ritzgen`.
- a function runs from its `fn` line to the next code line indented no deeper
  than the `fn`; its length is the code lines in that span.
- a cycle is a strongly connected component of the import graph with more than
  one module.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

BEGIN = "<!-- BEGIN generated by tools/ritz1_arch.py -->"
END = "<!-- END generated by tools/ritz1_arch.py -->"
LONG_FN = 300
DEFAULT_SRC = Path(__file__).resolve().parent.parent / "ritz1" / "src"

IMPORT_RE = re.compile(r"^[ \t]*(?:pub[ \t]+)?import[ \t]+([A-Za-z_][\w.]*)")
FN_RE = re.compile(r"^([ \t]*)(?:pub[ \t]+)?fn[ \t]+([A-Za-z_]\w*)")


@dataclass
class Fn:
    name: str
    line: int
    code: int


@dataclass
class Module:
    name: str
    lines: int = 0
    code: int = 0
    generated: bool = False
    imports: list[str] = field(default_factory=list)
    ritzlib: list[str] = field(default_factory=list)
    fns: list[Fn] = field(default_factory=list)


def _is_code(line: str) -> bool:
    s = line.strip()
    return bool(s) and not s.startswith("#")


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" \t"))


def _functions(lines: list[str]) -> list[Fn]:
    fns: list[Fn] = []
    for i, line in enumerate(lines):
        m = FN_RE.match(line)
        if not m:
            continue
        depth, code = len(m.group(1)), 1
        for body in lines[i + 1 :]:
            if not _is_code(body):
                continue
            if _indent(body) <= depth:
                break
            code += 1
        fns.append(Fn(m.group(2), i + 1, code))
    return fns


def scan(src: Path) -> dict[str, Module]:
    """Measure every `*.ritz` directly in `src`."""
    files = sorted(src.glob("*.ritz"))
    names = {f.stem for f in files}
    mods: dict[str, Module] = {}
    for f in files:
        lines = f.read_text(errors="replace").splitlines()
        mod = Module(f.stem, lines=len(lines))
        mod.code = sum(1 for ln in lines if _is_code(ln))
        mod.generated = bool(lines) and lines[0].startswith("# Generated by ritzgen")
        local, lib = set(), set()
        for ln in lines:
            m = IMPORT_RE.match(ln)
            if not m:
                continue
            name = m.group(1)
            if name.startswith("ritzlib."):
                lib.add(name[len("ritzlib.") :])
            elif name in names and name != mod.name:
                local.add(name)
        mod.imports, mod.ritzlib = sorted(local), sorted(lib)
        mod.fns = _functions(lines)
        mods[mod.name] = mod
    return mods


def _sccs(mods: dict[str, Module]) -> list[list[str]]:
    """Tarjan's algorithm; each component sorted, dependencies first."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    stack: list[str] = []
    on: set[str] = set()
    out: list[list[str]] = []

    def visit(v: str) -> None:
        index[v] = low[v] = len(index)
        stack.append(v)
        on.add(v)
        for w in mods[v].imports:
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            out.append(sorted(comp))

    sys.setrecursionlimit(max(1000, 10 * len(mods)))
    for v in sorted(mods):
        if v not in index:
            visit(v)
    return out


def cycles(mods: dict[str, Module]) -> list[list[str]]:
    return sorted(c for c in _sccs(mods) if len(c) > 1)


def dep_order(mods: dict[str, Module]) -> list[str]:
    """Modules with every import before its importer; ties alphabetical."""
    comps = _sccs(mods)
    owner = {m: i for i, c in enumerate(comps) for m in c}
    deps = {
        i: {owner[d] for m in c for d in mods[m].imports} - {i}
        for i, c in enumerate(comps)
    }
    done: set[int] = set()
    order: list[str] = []
    while len(done) < len(comps):
        ready = [i for i in deps if i not in done and deps[i] <= done]
        nxt = min(ready, key=lambda i: comps[i][0])
        done.add(nxt)
        order += comps[nxt]
    return order


def render(mods: dict[str, Module], long_fn: int = LONG_FN) -> str:
    importers = {m: sum(m in x.imports for x in mods.values()) for m in mods}
    gen = [m for m in sorted(mods) if mods[m].generated]
    total = sum(m.lines for m in mods.values())
    code = sum(m.code for m in mods.values())
    gen_lines = sum(mods[m].lines for m in gen)
    fns = [(f, m) for m in mods.values() for f in m.fns]
    long = sorted(
        ((f, m) for f, m in fns if f.code > long_fn),
        key=lambda p: (-p[0].code, p[1].name),
    )
    cyc = cycles(mods)
    edges = sum(len(m.imports) for m in mods.values())

    o = [BEGIN, ""]
    o.append(
        f"`ritz1/src/` has **{len(mods)}** modules, **{total}** lines "
        f"(**{code}** code lines, excluding blanks and comments), "
        f"**{len(fns)}** functions and **{edges}** local import edges. "
        f"{len(gen)} modules ({gen_lines} lines) are generated by ritzgen: "
        + (", ".join(f"`{m}`" for m in gen) or "none")
        + "."
    )
    o += ["", "### Modules in dependency order", ""]
    o.append(
        "Every module appears after all the modules it imports (modules in a cycle are adjacent). "
        "`(gen)` marks generated modules."
    )
    o += [
        "",
        "| Module | Imported by | Lines | Code | Local imports |",
        "|---|--:|--:|--:|---|",
    ]
    for name in dep_order(mods):
        m = mods[name]
        label = f"`{name}`" + (" (gen)" if m.generated else "")
        imps = ", ".join(m.imports) or "—"
        o.append(f"| {label} | {importers[name]} | {m.lines} | {m.code} | {imps} |")

    o += ["", "### Import cycles", ""]
    if not cyc:
        o.append("No import cycles.")
    else:
        o.append(
            f"{len(cyc)} import cycle{'s' if len(cyc) != 1 else ''} "
            "(strongly connected components of more than one module):"
        )
        o.append("")
        for c in cyc:
            o.append(f"- {len(c)} modules: " + " ↔ ".join(f"`{m}`" for m in c))

    users: dict[str, int] = {}
    for m in mods.values():
        for lib in m.ritzlib:
            users[lib] = users.get(lib, 0) + 1
    o += ["", "### ritzlib modules imported", ""]
    o.append(
        f"{len(users)} ritzlib modules, each with the number of ritz1 modules importing it: "
        + (", ".join(f"`{k}` ({v})" for k, v in sorted(users.items())) or "none")
        + "."
    )

    o += ["", "### Long functions", ""]
    o.append(f"{len(long)} functions longer than {long_fn} code lines:")
    if long:
        o += ["", "| Function | Module:line | Code lines |", "|---|---|--:|"]
        o += [f"| `{f.name}` | `{m.name}:{f.line}` | {f.code} |" for f, m in long]
    o += ["", END, ""]
    return "\n".join(o)


def replace_block(doc: str, block: str) -> str:
    start, end = doc.find(BEGIN), doc.find(END)
    if start < 0 or end < start:
        raise ValueError(f"document has no {BEGIN} ... {END} block")
    tail = doc[end + len(END) :]
    return doc[:start] + block.rstrip("\n") + tail


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--src", type=Path, default=DEFAULT_SRC)
    ap.add_argument("--long-fn", type=int, default=LONG_FN)
    act = ap.add_mutually_exclusive_group()
    act.add_argument("--write", type=Path, metavar="DOC")
    act.add_argument("--check", type=Path, metavar="DOC")
    args = ap.parse_args(argv)

    block = render(scan(args.src), args.long_fn)
    if args.write:
        args.write.write_text(replace_block(args.write.read_text(), block))
    elif args.check:
        doc = args.check.read_text()
        if replace_block(doc, block) != doc:
            print(
                f"{args.check} is stale: run tools/ritz1_arch.py --write {args.check}",
                file=sys.stderr,
            )
            return 1
    else:
        sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
